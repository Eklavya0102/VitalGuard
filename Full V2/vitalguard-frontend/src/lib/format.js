export const isNum = v => v !== null && v !== undefined && v !== '' && Number.isFinite(Number(v));

export const fmt = (v, digits = 1) => (isNum(v) ? Number(v).toFixed(digits) : '—');

/** Fraction (0–1) → percentage string. */
export const pct = (v, digits = 1) => (isNum(v) ? `${(Number(v) * 100).toFixed(digits)}%` : '—');

export const titleCase = s =>
  String(s ?? 'unknown').replace(/[_-]+/g, ' ').replace(/\s+/g, ' ').trim().replace(/\b\w/g, c => c.toUpperCase());

/** Provenance labels. `source` is the app-level source: python | python_fallback | matlab | upload. */
export function sourceInfo(source) {
  switch (source) {
    case 'python':
      return { label: 'Simulated · Python', kind: 'simulated', detail: 'Synthetic data generated by the backend Python simulator.' };
    case 'python_fallback':
      return { label: 'Simulated · Python (MATLAB fallback)', kind: 'simulated', detail: 'MATLAB was requested but the backend fell back to its Python simulator.' };
    case 'matlab':
      return { label: 'Simulated · MATLAB', kind: 'simulated', detail: 'Synthetic data generated by the backend MATLAB/Simulink adapter.' };
    case 'upload':
      return { label: 'Uploaded CSV', kind: 'uploaded', detail: 'Rows parsed by the backend from a CSV file you supplied.' };
    default:
      return { label: 'No dataset', kind: 'none', detail: 'No dataset is loaded.' };
  }
}

/** /analyze only accepts matlab | python | upload. */
export function analysisSourceFor(source) {
  if (source === 'python_fallback') return 'python';
  return source === 'matlab' || source === 'upload' ? source : 'python';
}

export function toCsv(rows) {
  if (!rows?.length) return '';
  const cols = [...new Set(rows.flatMap(r => Object.keys(r)))];
  const esc = v => {
    if (v === null || v === undefined) return '';
    const s = String(v);
    return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  return [cols.join(','), ...rows.map(r => cols.map(c => esc(r[c])).join(','))].join('\n');
}

export function downloadText(filename, text, mime = 'text/plain') {
  const blob = new Blob([text], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

