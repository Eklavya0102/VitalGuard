import { useState } from 'react';
import Icon from '../components/Icon';
import { Chip, Callout, PageHead, Panel, Empty, Provenance } from '../components/ui';
import { api } from '../api';
import { downloadText, timeLabel } from '../lib/format';
import { REPORT_FORMATS } from '../lib/meta';

export default function ReportsPage({ analysis, source, metadata, reports, setReports, setPage, toast }) {
  const [format, setFormat] = useState('summary');
  const [busy, setBusy] = useState(false);
  const [selected, setSelected] = useState(null); // index into reports
  const current = selected !== null ? reports[selected] : reports[0];

  const generate = async () => {
    if (!analysis) { toast('Analyze a dataset before generating a report.', 'error'); return; }
    setBusy(true);
    try {
      const r = await api.report({ analysis_result: analysis, format, include_raw_data: false });
      if (!r.success) throw new Error('The backend did not generate the report.');
      const text = typeof r.content === 'string' ? r.content : JSON.stringify(r.content, null, 2);
      const entry = { filename: r.filename, format: r.format || format, text, time: timeLabel(), backendTime: r.timestamp, source, label: metadata?.scenario_name || metadata?.filename || 'Dataset' };
      setReports(prev => [entry, ...prev].slice(0, 12));
      setSelected(null);
      toast(`${REPORT_FORMATS[format].label} report generated.`, 'success');
    } catch (err) {
      toast(`Report generation failed: ${err.message}`, 'error');
    } finally {
      setBusy(false);
    }
  };

  const save = e => downloadText(e.filename, e.text, REPORT_FORMATS[e.format]?.mime || 'text/plain');
  const copy = async e => {
    try { await navigator.clipboard.writeText(e.text); toast('Report copied to clipboard.', 'success'); }
    catch { toast('Copy is not available in this browser context.', 'error'); }
  };

  return (
    <div className="page">
      <PageHead eyebrow="Workspace" title="Reports" lead="Reports are generated by the backend from the most recent analysis held in this browser session." />

      <div className="grid-split">
        <Panel title="Generate report" aside={<Chip tone={analysis ? 'good' : 'neutral'}>{analysis ? 'Analysis available' : 'Analysis required'}</Chip>}>
          {!analysis ? (
            <Empty title="No analysis to report" actions={<button className="btn btn-primary" onClick={() => setPage('simulation')}>Start a simulation</button>}>
              Analyze a simulated or imported dataset first.
            </Empty>
          ) : (
            <>
              <div className="prov-row"><Provenance source={source} metadata={metadata} /></div>
              <fieldset className="radio-group">
                <legend>Format</legend>
                {Object.entries(REPORT_FORMATS).map(([k, f]) => (
                  <label key={k} className={`radio ${format === k ? 'on' : ''}`}>
                    <input type="radio" name="fmt" value={k} checked={format === k} onChange={() => setFormat(k)} />
                    <span><strong>{f.label} <small>.{f.ext}</small></strong><small>{f.description}</small></span>
                  </label>
                ))}
              </fieldset>
              <button className="btn btn-primary btn-block" onClick={generate} disabled={busy}>
                {busy ? <><span className="spinner" /> Generating…</> : 'Generate report'}
              </button>
              <p className="hint">Raw samples are not part of backend reports. Download them separately from the Signal analysis page.</p>
            </>
          )}
          <Callout tone="info" title="About report wording">The disclaimer text inside a report file is written by the backend. This application’s own disclaimer, shown at the foot of every page, is the reference statement.</Callout>
        </Panel>

        <Panel title="Report preview" sub={current ? `${current.filename} · generated ${current.time}` : 'Generated reports appear here.'}
          aside={current ? <div className="btn-row tight"><button className="btn btn-secondary btn-sm" onClick={() => copy(current)}><Icon name="copy" size={14} /> Copy</button><button className="btn btn-primary btn-sm" onClick={() => save(current)}><Icon name="download" size={14} /> Download</button></div> : null}>
          {!current ? <Empty title="Nothing generated yet">Choose a format and generate a report to preview it before downloading.</Empty> : (
            <pre className="report-pre" tabIndex={0} aria-label="Report content">{current.text}</pre>
          )}

          {reports.length > 0 && (
            <>
              <h3>This session</h3>
              <ul className="history">
                {reports.map((r, i) => (
                  <li key={`${r.filename}-${i}`} className={r === current ? 'on' : ''}>
                    <button className="link-btn" onClick={() => setSelected(i)}>{r.filename}</button>
                    <span className="muted small">{r.format.toUpperCase()} · {r.label} · {r.time}</span>
                    <button className="icon-btn sm" onClick={() => save(r)} aria-label={`Download ${r.filename}`}><Icon name="download" size={14} /></button>
                  </li>
                ))}
              </ul>
              <p className="hint">Kept in memory only; cleared when the page is reloaded.</p>
            </>
          )}
        </Panel>
      </div>
    </div>
  );
}
