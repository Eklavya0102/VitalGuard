import { useState } from 'react';
import { Link } from 'react-router-dom';
import { CheckCircle2, FileText } from 'lucide-react';
import { useApp } from '../context/AppContext';
import { useToast } from '../context/ToastContext';
import { postReport } from '../services/api';
import PageHeader from '../components/PageHeader';
import Badge from '../components/Badge';
import EmptyState from '../components/EmptyState';
import Busy from '../components/Spinner';
import { downloadText } from '../utils/download';
import { timeLabel } from '../utils/format';

export default function Reports() {
  const { analysis, reports, addReport } = useApp();
  const toast = useToast();
  const [format, setFormat] = useState('summary');
  const [busy, setBusy] = useState(false);
  const [last, setLast] = useState(null);

  async function generate() {
    if (!analysis) return toast('Analyze a dataset before generating a report.', 'error');
    setBusy(true);
    try {
      const r = await postReport({ analysis_result: analysis, format, include_raw_data: false });
      if (!r.success) throw new Error('Report generation failed');
      const content = typeof r.content === 'string' ? r.content : JSON.stringify(r.content, null, 2);
      const mime = format === 'json' ? 'application/json' : format === 'csv' ? 'text/csv' : 'text/plain';
      const filename = r.filename || `vitalguard-report.${format === 'summary' ? 'txt' : format}`;
      downloadText(content, filename, mime);
      addReport({ filename: r.filename || 'vitalguard-report', format, time: timeLabel() });
      setLast(r.filename || 'Report');
      toast('Report generated and downloaded.', 'success');
    } catch (e) {
      toast(`Report generation failed: ${e.message}`, 'error');
    } finally {
      setBusy(false);
    }
  }

  return (
    <>
      <PageHeader title="Reports" description="Generate a shareable export from the latest analysis result." />
      <section className="panel" aria-labelledby="rep-h">
        <div className="panel-head ruled">
          <div><h2 id="rep-h">Analysis report</h2><p>Report content is generated by the existing backend.</p></div>
          <Badge tone={analysis ? 'good' : 'neutral'}>{analysis ? 'Analysis available' : 'Analysis required'}</Badge>
        </div>
        {analysis ? (
          <>
            <div className="report-options">
              <label htmlFor="reportFormat">Format</label>
              <select id="reportFormat" value={format} onChange={(e) => setFormat(e.target.value)}>
                <option value="summary">Summary (.txt)</option>
                <option value="json">JSON (.json)</option>
                <option value="csv">CSV (.csv)</option>
              </select>
              <button className="btn btn-primary" onClick={generate} disabled={busy}>
                <Busy busy={busy} label="Generating…">Generate and download</Busy>
              </button>
            </div>
            <p className="panel-desc gap-top">This report uses the most recent analysis held in this browser session. Raw signal samples are not included unless the backend report implementation adds them.</p>
          </>
        ) : (
          <EmptyState
            icon={FileText}
            title="No analysis to report"
            actions={<Link className="btn btn-primary" to="/simulation">Start a simulation</Link>}
          >
            Analyze a simulated or imported dataset before generating a report.
          </EmptyState>
        )}
        {last && (
          <div className="notice notice-ok" role="status">
            <CheckCircle2 size={18} aria-hidden="true" />
            <div><strong>Report generated</strong><span>{last} was generated by the backend and downloaded.</span></div>
          </div>
        )}
        {reports.length > 0 && (
          <>
            <h3 className="gap-top">Generated this session</h3>
            <ul className="activity">
              {reports.slice(0, 5).map((r, i) => (
                <li key={i}>
                  <div><strong>{r.filename}</strong><small>{r.format.toUpperCase()} · {r.time}</small></div>
                  <Badge tone="good">Ready</Badge>
                </li>
              ))}
            </ul>
          </>
        )}
      </section>
    </>
  );
}
