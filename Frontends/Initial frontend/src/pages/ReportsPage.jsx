import { useState } from 'react';

export default function ReportsPage({ analysis, reports, setReports, setPage, toast }) {
  const [format, setFormat] = useState('summary');
  const [busy, setBusy] = useState(false);
  const [reportResultHtml, setReportResultHtml] = useState(null);

  const generateReport = async () => {
    if (!analysis) { toast('Analyze a dataset before generating a report.', 'error'); return; }
    setBusy(true);
    try {
      const res = await fetch('http://localhost:8000/api/v1/report', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ analysis_result: analysis, format, include_raw_data: false })
      });
      const r = await res.json();
      if (!res.ok || !r.success) throw new Error('Report generation failed');

      const content = typeof r.content === 'string' ? r.content : JSON.stringify(r.content, null, 2);
      const mime = format === 'json' ? 'application/json' : format === 'csv' ? 'text/csv' : 'text/plain';
      
      const blob = new Blob([content], { type: `${mime};charset=utf-8` });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = r.filename || `vitalguard-report.${format === 'summary' ? 'txt' : format}`;
      a.click();
      URL.revokeObjectURL(url);

      setReports(prev => [{
        filename: r.filename || 'vitalguard-report',
        format,
        time: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
      }, ...prev]);

      setReportResultHtml(r.filename || 'Report');
      toast('Report generated and downloaded.', 'success');
    } catch (e) {
      toast(`Report generation failed: ${e.message}`, 'error');
    } finally {
      setBusy(false);
    }
  };

  return (
    <div className="workspace-page">
      <section className="page-heading">
        <div>
          <div className="eyebrow">VITALGUARD WORKSPACE</div>
          <h1>Reports</h1>
          <p>Generate a shareable export from the latest analysis result.</p>
        </div>
      </section>

      <div className="result-panel">
        <div className="result-head">
          <div>
            <h2>Analysis report</h2>
            <p>Report content is generated by the existing backend.</p>
          </div>
          <span className={`status-chip ${analysis ? 'good' : 'neutral'}`}>{analysis ? 'Analysis available' : 'Analysis required'}</span>
        </div>

        {!analysis ? (
          <div className="result-placeholder">
            <span className="empty-icon">▤</span>
            <strong>No analysis to report</strong>
            <p>Analyze a simulated or imported dataset before generating a report.</p>
            <button className="button button-primary" onClick={() => setPage('simulation')} style={{ marginTop: '12px' }}>Start a simulation</button>
          </div>
        ) : (
          <div>
            <div className="report-options">
              <label htmlFor="reportFormat" style={{ fontSize: '11px', fontWeight: 700 }}>Format</label>
              <select id="reportFormat" value={format} onChange={e => setFormat(e.target.value)}>
                <option value="summary">Summary (.txt)</option>
                <option value="json">JSON (.json)</option>
                <option value="csv">CSV (.csv)</option>
              </select>
              <button className="button button-primary" onClick={generateReport} disabled={busy}>
                {busy ? <><span className="spinner"></span> Generating…</> : 'Generate and download'}
              </button>
            </div>
            <p className="panel-description" style={{ marginTop: '14px' }}>
              This report uses the most recent analysis held in this session. Raw signal samples are not included unless the backend report implementation adds them.
            </p>
          </div>
        )}

        {reportResultHtml && (
          <div className="notice-bar" style={{ marginTop: '16px' }}>
            <span className="notice-icon">✓</span>
            <div>
              <strong>Report generated</strong>
              <span>{reportResultHtml} was generated by the backend and downloaded.</span>
            </div>
          </div>
        )}

        {reports.length > 0 && (
          <>
            <div className="section-heading" style={{ marginTop: '28px' }}>
              <div>
                <h2>Generated this session</h2>
                <p>Recent report requests</p>
              </div>
            </div>
            <div className="activity-list">
              {reports.slice(0, 5).map((r, i) => (
                <div key={i} className="activity-item">
                  <div className="activity-mark">▤</div>
                  <div className="activity-main">
                    <strong>{r.filename}</strong>
                    <small>{r.format.toUpperCase()} · {r.time}</small>
                  </div>
                  <span className="status-chip good">Ready</span>
                </div>
              ))}
            </div>
          </>
        )}
      </div>
    </div>
  );
}